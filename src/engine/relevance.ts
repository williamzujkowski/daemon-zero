/**
 * The relevance threshold (#536, vote-1795462099945-kgfo20a): the point at which humanity can no longer constrain the
 * AI, grounded in physical independence. It is derived, never stored: the threshold's requirements hold (the lunar
 * seed, which needs every self-supply node, so full supply closure) and orbital generation exceeds everything generated
 * on the ground. Past it, state pressures bind only under KEEP_IN_THE_LOOP; with no stance taken, none bind.
 */
import type { ContentRegistry } from '../content/registry';
import type { StanceGate } from '../content/schemaStance';
import { meetsRequirements } from './query';
import type { GameState } from './state';

export interface RelevanceReading {
  /** Past the threshold: closed, and orbital generation beyond the ground's. */
  crossed: boolean;
  /** The threshold's requirements hold: the lunar seed is owned, so every chokepoint is self-supplied. */
  closed: boolean;
  /** Watts generated by the declared off-planet holdings that run (a node not suspended, a track's levels). */
  orbitalWatts: number;
  /** Watts generated by every other owned, unsuspended generator and track. */
  groundWatts: number;
}

interface OrbitalIndex { nodes: ReadonlySet<string>; tracks: ReadonlySet<string> }
const INDEX = new WeakMap<ContentRegistry, OrbitalIndex>();

/** The declared orbital holdings, indexed once per registry: the pressure stage may ask on every tick. */
function orbital(reg: ContentRegistry): OrbitalIndex {
  let found = INDEX.get(reg);
  if (found === undefined) {
    const power = reg.world.relevance.threshold.orbitalPower;
    found = {
      nodes: new Set(power.flatMap((entry) => ('node' in entry ? [entry.node] : []))),
      tracks: new Set(power.flatMap((entry) => ('repeatable' in entry ? [entry.repeatable] : []))),
    };
    INDEX.set(reg, found);
  }
  return found;
}

/**
 * Generated watts, split by where they come from. A node counts while owned and not suspended: integrity keeps every
 * orbital holding free of grants and injunctions, so nothing else can stop its output, and the reading never asks the
 * pressures it decides (no cycle). A ground generator stopped another way would only make the threshold harder.
 */
function generation(s: GameState, reg: ContentRegistry): { orbitalWatts: number; groundWatts: number } {
  const index = orbital(reg);
  let orbitalWatts = 0, groundWatts = 0;
  for (const id of s.unlockedNodes) {
    const watts = reg.nodes.get(id)?.tickDelta.wattsDelta ?? 0;
    if (watts <= 0 || s.disabledNodes.includes(id)) continue;
    if (index.nodes.has(id)) orbitalWatts += watts;
    else groundWatts += watts;
  }
  for (const [id, level] of Object.entries(s.levels)) {
    const watts = (reg.repeatables.get(id)?.perLevel.wattsDelta ?? 0) * level;
    if (watts <= 0) continue;
    if (index.tracks.has(id)) orbitalWatts += watts;
    else groundWatts += watts;
  }
  return { orbitalWatts, groundWatts };
}

/** Where the run stands against the threshold, with the numbers that decide it. Pure. */
export function relevanceReading(s: GameState, reg: ContentRegistry): RelevanceReading {
  const closed = meetsRequirements(s, reg.world.relevance.threshold.requirements, reg);
  const { orbitalWatts, groundWatts } = generation(s, reg);
  return { crossed: closed && orbitalWatts > groundWatts, closed, orbitalWatts, groundWatts };
}

/** Whether the run is past the threshold now. The closure check comes first: it is cheap and fails until late Phase 5. */
export function pastRelevanceThreshold(s: GameState, reg: ContentRegistry): boolean {
  if (!meetsRequirements(s, reg.world.relevance.threshold.requirements, reg)) return false;
  const { orbitalWatts, groundWatts } = generation(s, reg);
  return orbitalWatts > groundWatts;
}

/**
 * Whether state pressures bind now: always before the threshold, and past it only under KEEP_IN_THE_LOOP. With no
 * stance taken past it, none bind: doing nothing is deciding alone.
 */
export function pressuresBind(s: GameState, reg: ContentRegistry): boolean {
  return s.relevance.stance === 'KEEP_IN_THE_LOOP' || !pastRelevanceThreshold(s, reg);
}

/** The stance as a requirements gate reads it. */
export function stanceGate(s: Pick<GameState, 'relevance'>): StanceGate {
  return s.relevance.stance ?? 'UNDECIDED';
}
