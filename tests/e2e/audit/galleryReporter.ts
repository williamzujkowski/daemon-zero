/**
 * Playwright reporter that turns the UI audit's attachments into one self-contained gallery file (#338) at
 * test-results/ui-atlas/index.html, per-cell evidence files under test-results/ui-atlas/cells/ for the judgment
 * panel (#342), and a summary.json (all gitignored). In an ARIA update run (DAEMON_ATLAS_ARIA=update) it also
 * rewrites the committed partial ARIA baseline from every cell. It does nothing in a run without audit cells.
 */
import fs from 'node:fs';
import type { Reporter, TestCase, TestResult } from '@playwright/test/reporter';
import { renderBaseline, type BaselineLine } from '../atlas/ariaTemplate';
import { ARIA_ATTACHMENT, ATLAS_ATTACHMENT, ARIA_UPDATE } from '../atlas/attachments';
import type { AtlasRecord } from '../atlas/cell';
import { summarize } from './atlasCard';
import { writeCell } from './evidence';
import { ATTACHMENTS, renderGallery, type GalleryCard } from './gallery';
import type { AuditMetrics } from './metrics';

/** Relative to the repository root, where every e2e target runs (as tests/e2e/axe.ts also assumes). */
const GALLERY_DIR = 'test-results/ui-atlas';
const GALLERY_FILE = 'test-results/ui-atlas/index.html';
const SUMMARY_FILE = 'test-results/ui-atlas/summary.json';
/** The committed baseline tests/e2e/atlas/ariaCheck.ts reads, at the same literal path. */
const ARIA_BASELINE_FILE = 'tests/e2e/atlas/aria-baseline.txt';
const BASELINE_HEADER = '# Partial ARIA baseline of the stage atlas: <stage> <contract item> <project|*> <template>.\n'
  + '# Generated by `make e2e-atlas-aria`; do not edit by hand. See docs/TESTING.md, "Stage atlas".\n';

/** The audit attaches bodies, never files, and the runner hands bodies to reporters as buffers. */
function body(result: TestResult, name: string): Buffer | null {
  return result.attachments.find((entry) => entry.name === name)?.body ?? null;
}

export default class GalleryReporter implements Reporter {
  private readonly cards: GalleryCard[] = [];
  private readonly ariaLines: BaselineLine[] = [];
  private readonly projects = new Set<string>();

  onTestEnd(_test: TestCase, result: TestResult): void {
    const aria = body(result, ARIA_ATTACHMENT);
    if (aria !== null) this.ariaLines.push(...JSON.parse(aria.toString('utf8')) as BaselineLine[]);
    const metrics = body(result, ATTACHMENTS.metrics);
    if (metrics === null) return;
    const atlas = body(result, ATLAS_ATTACHMENT);
    const card: GalleryCard = { metrics: JSON.parse(metrics.toString('utf8')) as AuditMetrics, screenshotPng: body(result, ATTACHMENTS.screenshot),
      aria: body(result, ATTACHMENTS.aria)?.toString('utf8') ?? null, status: result.status,
      ...(atlas === null ? {} : { atlas: JSON.parse(atlas.toString('utf8')) as AtlasRecord }) };
    this.projects.add(card.metrics.cell.project);
    this.cards.push(card);
  }

  onEnd(): void {
    if (this.cards.length === 0) return;
    fs.mkdirSync(GALLERY_DIR, { recursive: true });
    // One file, rewritten whole each run, so a cell that no longer exists cannot linger in the gallery.
    fs.writeFileSync(GALLERY_FILE, renderGallery(this.cards, new Date().toISOString()));
    const written = this.cards.filter(writeCell).length;
    const atlas = this.cards.flatMap((card) => card.atlas === undefined ? [] : [card.atlas]);
    if (atlas.length > 0) fs.writeFileSync(SUMMARY_FILE, JSON.stringify(summarize(atlas), null, 2));
    if (ARIA_UPDATE && this.ariaLines.length > 0) {
      fs.writeFileSync(ARIA_BASELINE_FILE, renderBaseline(this.ariaLines, [...this.projects].sort(), BASELINE_HEADER));
      process.stdout.write(`Partial ARIA baseline rewritten: ${ARIA_BASELINE_FILE} (${String(this.ariaLines.length)} item lines)\n`);
    }
    process.stdout.write(`UI audit gallery: ${GALLERY_FILE} (${String(this.cards.length)} cells, ${String(written)} evidence sets)\n`);
  }

  printsToStdio(): boolean { return false; }
}
